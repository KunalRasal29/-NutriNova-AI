def _expanded_food(
    number: int,
    canonical_name: str,
    country_code: str,
    serving_description: str,
    default_serving_g: str,
    aliases: list[str],
    nutrients: dict[str, str],
    *,
    brand_name: str = "",
    food_type: str = Food.FoodType.GENERIC,
    region: str = "",
    description: str = "",
    barcode: str = "",
    verified: bool = False,
    confidence_score: str = "0.7200",
    data_quality_score: str = "0.7200",
    servings: list[dict[str, str | bool]] | None = None,
    metadata: dict | None = None,
):
    return {
        "canonical_name": canonical_name,
        "external_id": f"POPULAR-{number:03d}",
        "brand_name": brand_name,
        "food_type": food_type,
        "country_code": country_code,
        "region": region,
        "description": description,
        "barcode": barcode,
        "serving_description": serving_description,
        "default_serving_g": default_serving_g,
        "data_quality_score": data_quality_score,
        "confidence_score": confidence_score,
        "verified": verified,
        "aliases": aliases,
        "servings": servings or _servings_for(serving_description, default_serving_g),
        "metadata": metadata or {},
        "nutrients": nutrients,
    }


def _servings_for(
    serving_description: str,
    grams: str,
    extra: list[tuple[str, str]] | None = None,
) -> list[dict[str, str | bool]]:
    entries: list[tuple[str, str, bool]] = [(serving_description, grams, True)]
    description = serving_description.lower()
    if serving_description.lower() != "100 g":
        entries.append(("100 g", "100.00", False))
    if "bowl" in description:
        entries.extend([("1 katori", grams, False), ("1 serving", grams, False)])
    if "plate" in description:
        entries.append(("1 serving", grams, False))
    if "cup" in description:
        entries.append(("1 cup", grams, False))
    if "glass" in description:
        entries.append(("1 glass", grams, False))
    if "scoop" in description:
        entries.append(("1 scoop", grams, False))
    if "packet" in description or "pack" in description:
        entries.append(("1 packet", grams, False))
    if "slice" in description:
        entries.append(("1 slice", grams, False))
    if any(word in description for word in ("egg", "idli", "dosa", "roti", "chapati")):
        entries.append(("1 piece", grams, False))
    for name, weight in extra or []:
        entries.append((name, weight, False))

    seen = set()
    servings = []
    for name, weight, is_default in entries:
        key = name.lower()
        if key in seen:
            continue
        seen.add(key)
        servings.append(
            {
                "serving_name": name,
                "grams": weight,
                "household_quantity": name,
                "is_default": is_default,
            }
        )
    return servings


