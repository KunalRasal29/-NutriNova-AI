def _phase12_food(
    number: int,
    canonical_name: str,
    country_code: str,
    serving_description: str,
    default_serving_g: str,
    aliases: list[str],
    calories: str,
    protein: str,
    carbs: str,
    fat: str,
    *,
    extra_nutrients: dict[str, str] | None = None,
    brand_name: str = "",
    food_type: str = Food.FoodType.GENERIC,
    region: str = "",
    description: str = "",
    barcode: str = "",
    verified: bool = True,
    confidence_score: str = "0.8200",
    data_quality_score: str = "0.8200",
    extra_servings: list[tuple[str, str]] | None = None,
):
    nutrients = {
        "calories": calories,
        "protein_g": protein,
        "carbs_g": carbs,
        "fat_g": fat,
    }
    nutrients.update(extra_nutrients or {})
    is_estimated = food_type in {
        Food.FoodType.BRANDED,
        Food.FoodType.RESTAURANT,
    }
    metadata = {
        "seed_phase": "phase_12_food_database_accuracy",
        "private_beta": True,
        "accuracy_note": (
            "Common local seed value. Treat as a trusted starting point, "
            "but verify packaged labels and restaurant portions."
        ),
    }
    if barcode:
        metadata["sample_barcode"] = True
    if is_estimated:
        verified = False
        confidence_score = min(confidence_score, "0.7000")
        data_quality_score = min(data_quality_score, "0.7000")
        metadata["accuracy_note"] = (
            "Estimated branded/restaurant reference for private beta testing. "
            "Check the actual label or restaurant portion when precision matters."
        )
    return _expanded_food(
        number,
        canonical_name,
        country_code,
        serving_description,
        default_serving_g,
        aliases,
        nutrients,
        brand_name=brand_name,
        food_type=food_type,
        region=region,
        description=description,
        barcode=barcode,
        verified=verified,
        confidence_score=confidence_score,
        data_quality_score=data_quality_score,
        servings=_servings_for(serving_description, default_serving_g, extra_servings),
        metadata=metadata,
    )


