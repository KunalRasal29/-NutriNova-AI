def _finalize_popular_food_records():
    for record in POPULAR_FOODS:
        food_type = record.get("food_type", Food.FoodType.GENERIC)
        record["replace_aliases"] = True
        record.setdefault(
            "metadata",
            {
                "private_beta": True,
                "accuracy_note": (
                    "Approximate local seed value for private beta use. "
                    "Review packaged labels and restaurant portions when needed."
                ),
            },
        )
        record.setdefault(
            "servings",
            _servings_for(
                record.get("serving_description", "100 g"),
                str(record.get("default_serving_g") or "100.00"),
            ),
        )
        nutrients = record.get("nutrients", {})
        has_core_macros = all(
            code in nutrients for code in ("calories", "protein_g", "carbs_g", "fat_g")
        )
        if has_core_macros and food_type == Food.FoodType.GENERIC:
            record["verified"] = True
            record["data_quality_score"] = max(
                str(record.get("data_quality_score", "0.0000")),
                "0.8000",
            )
            record["confidence_score"] = max(
                str(record.get("confidence_score", "0.0000")),
                "0.8000",
            )


_finalize_popular_food_records()


class Command(BaseCommand):
    help = "Seed a larger local friends-beta food catalog for daily testing."

    def handle(self, *args, **options):
        seed_core_reference_data()
        source = get_manual_sample_source()
        job = create_import_job(source, file_name="seed_popular_foods")
        result = import_json_food_records(
            POPULAR_FOODS,
            source,
            default_food_type=Food.FoodType.GENERIC,
        )
        finish_import_job(job, result)
        self.stdout.write(
            self.style.SUCCESS(
                "Seeded popular foods: "
                f"{result.rows_created} created, {result.rows_updated} updated, "
                f"{len(result.errors or [])} errors."
            )
        )
